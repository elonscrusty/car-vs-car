# karts.json (from build.py) -> src/shared/KartMeshData.luau for the game's runtime builder.
import json, sys
src, dst = sys.argv[1], sys.argv[2]
k = json.load(open(src))
out = ["--!strict", "-- GENERATED by rc-test/assets/karts/ (build.py, then to_luau.py): don't edit by hand.",
       "-- The 6 karts' parts: vertices (x, y, z in hundredths of a toy unit; nose +Z, ground y = 0)",
       "-- and triangles (1-based vertex numbers). KartMesh builds them into MeshParts.",
       "export type Mesh = { v: string, t: string }", "", "return {"]
for name in sorted(k):
    out.append(f"\t{name} = {{")
    for g in sorted(k[name]):
        d = k[name][g]
        v = ",".join(str(int(round(c * 100))) for p in d["v"] for c in p)
        t = ",".join(str(i + 1) for tri in d["t"] for i in tri)
        out.append(f'\t\t{g} = {{ v = "{v}", t = "{t}" }},')
    out.append("\t},")
out.append("} :: { [string]: { [string]: Mesh } }")
open(dst, "w").write("\n".join(out) + "\n")
