# karts.json (from build.py) and carter1.json (from carter/meshy.py) -> src/shared/KartMeshData.luau
# for the game's runtime builder: python3 to_luau.py out/karts.json out/carter1.json <dst>
# Compact (Studio gets code pasted in, phones download it): every number is base-64 characters
# (shared/KartCode.luau decodes them), parts shared by several karts are stored once, and karts no
# car wears (ToyCars.KARTS) are left out. Kart_Racer is unused now (carter's kart replaced it).
import json, sys
*srcs, dst = sys.argv[1:]
SKIP = {"Kart_Racer"}
A = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
def two(n):
    assert 0 <= n < 4096, n
    return A[n // 64] + A[n % 64]
k = {}
for src in srcs:
    k.update(json.load(open(src)))
parts, ids, kart = [], {}, {}
for name in sorted(k):
    if name in SKIP:
        continue
    kart[name] = {}
    for g in sorted(k[name]):
        d = k[name][g]
        w = 1 if len(d["v"]) <= 64 else 2
        v = "".join(two(int(round(c * 100)) + 2048) for p in d["v"] for c in p)
        t = "".join((A[i] if w == 1 else two(i)) for tri in d["t"] for i in tri)
        key = (v, t)
        if key not in ids:
            ids[key] = len(parts) + 1
            parts.append(f'{{ v = "{v}", t = "{t}", w = {w} }}')
        kart[name][g] = ids[key]
out = ["--!strict", "-- GENERATED by rc-test/assets/karts/ (build.py and carter/meshy.py, then to_luau.py): don't edit by hand.",
       "-- The karts' parts: vertices (x, y, z in hundredths of a toy unit; nose +Z, ground y = 0) and",
       "-- triangles (vertex numbers), as base-64 characters (KartCode decodes them; w = characters per",
       "-- vertex number). Parts several karts share are stored once. KartMesh builds them into MeshParts.",
       "export type Mesh = { v: string, t: string, w: number }", "", "local P: { Mesh } = {"]
out += [f"\t{p}," for p in parts]
out += ["}", "", "return {"]
for name, gs in kart.items():
    out.append(f"\t{name} = {{")
    out += [f"\t\t{g} = P[{i}]," for g, i in gs.items()]
    out.append("\t},")
out.append("} :: { [string]: { [string]: Mesh } }")
open(dst, "w").write("\n".join(out) + "\n")
print(len(parts), "parts", sum(len(p) for p in parts), "chars")
